"""
Step 1 — โหลดภาพดอกทานตะวัน 50 ภาพจาก dataset PhotoArt50
วิชา 310-3311 Image Processing / Workshop ท้าย Lecture 10

โจทย์ (สไลด์หน้า 63)
    ข้อ 1  หาโจทย์การแบ่งส่วนวัตถุออกจากพื้นหลัง  -> เลือกดอกทานตะวัน
    ข้อ 2  หา Dataset อย่างน้อย 50 ภาพ            -> ไฟล์นี้ทำข้อนี้ครึ่งแรก
           (ครึ่งหลังคือ Ground truth อยู่ใน step2)

ที่มาของภาพ
    PhotoArt50 — University of Bath
    https://github.com/BathVisArtData/PhotoArt50
    คลาส 204.sunflower มีรูปถ่ายจริง 52 ภาพ เราเอา 50 ภาพแรก

ทำไมต้องมีไฟล์นี้ ทำไมไม่ commit ภาพขึ้น git ไปเลย
    1. เจ้าของ dataset เขียนไว้ว่าภาพหลายรูปติดลิขสิทธิ์ ให้ใช้เพื่อการศึกษาเท่านั้น
       เอาขึ้น repo สาธารณะของเราเท่ากับเผยแพร่ต่อ ซึ่งเขาไม่ได้อนุญาต
    2. เพื่อนอีกเครื่องรันไฟล์นี้แล้วจะได้ภาพ "ชุดเดียวกันเป๊ะ" กับเรา
       ถ้าต่างคนต่างโหลดเอง ภาพอาจไม่ตรงกัน แล้ว ground truth ที่ทำไว้จะใช้ข้ามเครื่องไม่ได้

ไฟล์นี้มี 2 def เรียงตามลำดับที่ใช้งานจริง
    1. download_one_image()   โหลดภาพทีละ 1 ไฟล์
    2. main()                 วนเรียก download_one_image() 50 รอบ

รัน:  python step1_download_images.py
      รันจากโฟลเดอร์ไหนก็ได้ หรือกดปุ่ม Run ใน VS Code ก็ได้
      เพราะโปรแกรมหาโฟลเดอร์ของตัวเองเจอ (ดู PROJECT_FOLDER ข้างล่าง)

ถ้าเน็ตหลุดกลางทาง ให้รันซ้ำได้เลย ไฟล์ที่โหลดไปแล้วจะถูกข้าม
"""

import os
import sys
import urllib.request


# ที่อยู่ของภาพดิบบน GitHub  (raw.githubusercontent.com คือที่ที่ให้โหลดไฟล์ตรงๆ
# ถ้าใช้ github.com ธรรมดาจะได้หน้าเว็บ HTML กลับมาแทนที่จะได้ไฟล์ภาพ)
BASE_URL = "https://raw.githubusercontent.com/BathVisArtData/PhotoArt50/master/204.sunflower"

# โฟลเดอร์ที่ไฟล์ .py นี้วางอยู่
#
# ทำไมต้องหาโฟลเดอร์ตัวเอง ทำไมไม่เขียน "dataset/images" ไปตรงๆ
#     ถ้าเขียนตรงๆ Python จะไปหาจาก "โฟลเดอร์ที่เทอร์มินัลยืนอยู่ตอนนั้น"
#     ไม่ใช่โฟลเดอร์ที่ไฟล์นี้วางอยู่ พอกดปุ่ม Run ใน VS Code มันยืนอยู่ที่โฟลเดอร์
#     ที่เปิดไว้ ซึ่งอาจไม่ใช่โฟลเดอร์โปรเจกต์ แล้วภาพจะไปโผล่ผิดที่โดยไม่ error
#     (เจอมาแล้วจริง ภาพ 50 ไฟล์ไปสร้างอยู่นอกโฟลเดอร์โปรเจกต์)
#
# __file__            = ที่อยู่ของไฟล์ .py นี้
# os.path.abspath()   = ทำให้เป็นที่อยู่เต็ม ไม่ใช่ที่อยู่แบบย่อ
# os.path.dirname()   = ตัดชื่อไฟล์ทิ้ง เหลือแต่ชื่อโฟลเดอร์
PROJECT_FOLDER = os.path.dirname(os.path.abspath(__file__))

# โฟลเดอร์ปลายทางที่จะเก็บภาพ
#
# os.path.join() ต่อ path ให้ โดยใส่เครื่องหมายคั่นให้ถูกตามระบบปฏิบัติการ
# Windows ใช้ \  ส่วน Mac ใช้ /  ถ้าเขียนเองต้องเลือกข้าง แล้วอีกเครื่องจะพัง
IMAGE_FOLDER = os.path.join(PROJECT_FOLDER, "dataset", "images")

# จำนวนภาพที่โจทย์ข้อ 2 ต้องการ
HOW_MANY_IMAGES = 50


# ====================================================================
#  1. download_one_image() — โหลดภาพทีละ 1 ไฟล์
# ====================================================================

def download_one_image(image_number):
    """
    โหลดภาพดอกทานตะวัน 1 ภาพ ตามหมายเลขที่ส่งเข้ามา

    รับ     : image_number เลขภาพ เช่น 1, 2, 3
    ส่งกลับ : ไม่ส่งอะไรกลับ แต่จะได้ไฟล์ใหม่ในโฟลเดอร์ dataset/images
    """

    # ชื่อไฟล์ใน dataset เขียนเลข 4 หลักเสมอ เช่น เลข 1 คือ 204p_0001.jpg
    # zfill(4) แปลว่า "เติมเลขศูนย์ข้างหน้าให้ครบ 4 ตัว"  1 -> "0001"
    file_name = "204p_" + str(image_number).zfill(4) + ".jpg"

    # ที่อยู่บนเว็บใช้ / เสมอทุกระบบ ต่อด้วย + ได้เลย
    image_url = BASE_URL + "/" + file_name

    # ส่วนที่อยู่ในเครื่อง ต้องใช้ os.path.join เพราะ Windows กับ Mac ใช้ตัวคั่นคนละตัว
    save_path = os.path.join(IMAGE_FOLDER, file_name)

    # ถ้าเคยโหลดไฟล์นี้ไปแล้ว ไม่ต้องโหลดซ้ำ
    # มีไว้เพื่อให้รันไฟล์นี้ซ้ำได้เรื่อยๆ โดยไม่เสียเวลาโหลดใหม่ทั้ง 50 ภาพ
    if os.path.exists(save_path):
        print("ข้าม   " + file_name + "  (มีอยู่แล้ว)")
        return

    # โหลดลงชื่อชั่วคราวก่อน ที่ลงท้ายด้วย .part แล้วค่อยเปลี่ยนเป็นชื่อจริงตอนโหลดจบ
    #
    # ทำไมต้องทำสองจังหวะ ทำไมไม่โหลดลงชื่อจริงไปเลย
    #     ถ้าเน็ตหลุดตอนกำลังโหลด จะเหลือไฟล์ที่โหลดไม่จบค้างอยู่ในชื่อจริง
    #     พอรันซ้ำ บรรทัด os.path.exists ข้างบนจะเห็นว่ามีไฟล์อยู่แล้ว แล้วข้ามไป
    #     ไฟล์เสียนั้นจะค้างอยู่ตลอดไป
    #
    #     ที่แย่คือมันไม่ error ให้เห็นเลย ทดลองแล้วโดยตัด 204p_0007.jpg ให้เหลือครึ่งเดียว
    #         cv2.imread ยังอ่านได้ ไม่คืน None แต่ข้อมูลผิดไป 115 จาก 194 แถว
    #         แล้ว step3 ตัดสินว่าเป็นดอกไม้ 25.6% แทนที่จะเป็น 48.4%
    #     คือผลผิดไปครึ่งหนึ่ง โดยไม่มีอะไรฟ้อง และเราจะไปนั่งระบายเฉลยทับภาพเสียนั้น
    #
    #     พอโหลดลงชื่อ .part ก่อน ถ้าเน็ตหลุด จะเหลือแค่ไฟล์ .part
    #     ชื่อจริงยังไม่เกิด บรรทัด os.path.exists จึงบอกถูกว่ายังไม่มี แล้วโหลดใหม่ให้
    temp_path = save_path + ".part"

    # urlretrieve = "ไปเอาไฟล์จาก URL นี้ มาเซฟไว้ที่ path นี้"
    urllib.request.urlretrieve(image_url, temp_path)

    # os.replace = เปลี่ยนชื่อไฟล์ บรรทัดนี้จะทำงานก็ต่อเมื่อบรรทัดบนโหลดจบแล้วเท่านั้น
    # ถ้าบรรทัดบนพัง โปรแกรมหยุดตรงนั้น ไม่มีทางมาถึงบรรทัดนี้
    os.replace(temp_path, save_path)

    print("โหลด   " + file_name)


# ====================================================================
#  2. main() — วนโหลดครบ 50 ภาพ
# ====================================================================

def main():
    """
    สร้างโฟลเดอร์ปลายทาง แล้ววนโหลดภาพตั้งแต่เลข 1 ถึง 50

    รับ     : ไม่รับอะไร
    ส่งกลับ : ไม่ส่งอะไรกลับ
    """

    # บังคับให้ข้อความที่ print ออกไป ใช้ตารางตัวอักษร utf-8 เสมอ
    #
    # ทำไมต้องมีบรรทัดนี้ (วัดมาแล้วบนเครื่องที่ใช้ทำโปรเจกต์นี้)
    #     รันใน PowerShell ตรงๆ        sys.stdout.encoding = utf-8   print ไทยได้
    #     รันแล้วส่ง output ไปที่อื่น    sys.stdout.encoding = cp1252  print ไทยแล้วพัง
    #     เช่น  python step1_download_images.py > log.txt
    #
    # เพราะเวลา output ไม่ได้ออกหน้าจอตรงๆ Python จะหันไปใช้ค่า locale ของเครื่องแทน
    # ซึ่งเครื่องนี้เป็น cp1252 (ตารางตัวอักษรยุโรปตะวันตก) ที่ไม่มีตัวอักษรไทยอยู่เลย
    # เจอ "ก" ปุ๊บก็แปลงไม่ออก แล้ว error UnicodeEncodeError ทันที
    #
    # reconfigure() = "เปลี่ยนการตั้งค่าของช่องทาง output ใหม่" สั่งให้ใช้ utf-8 ตายตัว
    # บน Mac ไม่มีผลอะไร เพราะเป็น utf-8 อยู่แล้ว แต่ใส่ไว้ให้โค้ดชุดเดียวรันได้ทุกเครื่อง
    #
    # ทำไมต้องอยู่ในนี้ ไม่ใช่ข้างนอกไฟล์
    #     ถ้าวางไว้ข้างนอก มันจะทำงานตอนที่ไฟล์อื่นสั่ง import ไฟล์นี้
    #     แปลว่าแค่ import ก็ไปแก้ช่องทาง output ของคนที่ import โดยที่เขาไม่ได้ขอ
    #     และถ้า output ของเขาไม่มีเมธอด reconfigure จะพังตั้งแต่บรรทัด import
    sys.stdout.reconfigure(encoding="utf-8")

    # exist_ok=True แปลว่า "ถ้าโฟลเดอร์มีอยู่แล้วก็ไม่ต้อง error"
    # ถ้าไม่ใส่ พอรันรอบที่ 2 จะพังทันทีเพราะโฟลเดอร์มีอยู่แล้ว
    os.makedirs(IMAGE_FOLDER, exist_ok=True)

    print("กำลังโหลดภาพลงโฟลเดอร์ " + IMAGE_FOLDER)
    print("")

    # range(1, 51) ให้เลข 1 ถึง 50  (ตัวหลังไม่ถูกนับ จึงต้องใส่ 51)
    for image_number in range(1, HOW_MANY_IMAGES + 1):
        download_one_image(image_number)

    # นับไฟล์จริงในโฟลเดอร์ เพื่อยืนยันว่าครบ 50 ตามโจทย์ข้อ 2
    #
    # ต้องนับเฉพาะ .jpg ไม่นับทุกไฟล์ที่เจอ
    # เพราะถ้าเน็ตหลุดกลางทาง จะมีไฟล์ .part ค้างอยู่ด้วย
    # ถ้านับรวมไปด้วย บรรทัดนี้จะขึ้นว่าครบ 50 ทั้งที่ภาพจริงมีแค่ 49
    # ซึ่งทำให้บรรทัดที่มีไว้ยืนยันโจทย์ กลายเป็นตัวโกหกเสียเอง
    image_count = 0
    for file_name in os.listdir(IMAGE_FOLDER):
        if file_name.endswith(".jpg"):
            image_count = image_count + 1

    print("")
    print("เสร็จแล้ว มีภาพในโฟลเดอร์ทั้งหมด " + str(image_count) + " ภาพ")


if __name__ == "__main__":
    main()
